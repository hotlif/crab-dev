import { readFile, writeFile } from 'node:fs/promises';

const packageRoot = new URL('../', import.meta.url);
const semanticSource = await readFile(new URL('token.toml', packageRoot), 'utf8');
const globalSource = await readFile(new URL('../rc-token-global/token.toml', packageRoot), 'utf8');

// This generator accepts the deliberately narrow density grammar: one-line
// string values that reference a positive L1 px primitive. It is not a TOML
// parser and rejects unsupported expressions instead of guessing CSS fallbacks.
function stringTokens(source) {
    const section = source.slice(source.indexOf('[token]') + '[token]'.length);
    return new Map([...section.matchAll(/^([\w.-]+)\s*=\s*("(?:\\.|[^"\\])*")\s*(?:#.*)?$/gm)]
        .map(([, name, value]) => [name, JSON.parse(value)]));
}

const semanticTokens = stringTokens(semanticSource);
const globalTokens = stringTokens(globalSource);
const densityGeometry = {};

for (const density of ['compact', 'standard', 'comfortable']) {
    const metrics = {};
    for (const metric of ['row', 'header', 'navigation', 'item']) {
        const name = `density.${density}.${metric}`;
        const value = semanticTokens.get(name);
        const reference = typeof value === 'string' ? /^\$ref\(([\w.-]+)\)$/.exec(value)?.[1] : undefined;
        const primitive = reference === undefined ? undefined : globalTokens.get(reference);
        const pixels = typeof primitive === 'string' ? /^(\d+(?:\.\d+)?)px$/.exec(primitive)?.[1] : undefined;
        if (pixels === undefined || Number(pixels) <= 0) {
            throw new Error(`${name} must reference a positive L1 px primitive; received ${String(value)}.`);
        }
        metrics[metric] = Number(pixels);
    }
    densityGeometry[density] = metrics;
}

const generated = '// Generated by scripts/generate-density-geometry.mjs from token.toml. Do not edit.\n'
    + `export const densityGeometry = ${JSON.stringify(densityGeometry, null, 4)} as const;\n\n`
    + 'export type Density = keyof typeof densityGeometry;\n';
const output = new URL('src/density-geometry.ts', packageRoot);
let previous;
try { previous = await readFile(output, 'utf8'); } catch (error) {
    if (error.code !== 'ENOENT') throw error;
}
if (previous !== generated) await writeFile(output, generated);
