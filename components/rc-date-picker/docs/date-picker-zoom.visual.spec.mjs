import { zoomTest, expect, configurations, openDemo, readVisualSpec, settleFiniteAnimations, captureZoom } from '../../../test/visual/component-fixture.mjs';

const spec = await readVisualSpec(import.meta.url);
async function expectPopupWithinWidth(page, dialog) {
    const width = await page.evaluate(() => globalThis.innerWidth);
    const popup = await dialog.boundingBox();
    expect(popup.x).toBeGreaterThanOrEqual(0);
    expect(popup.x + popup.width).toBeLessThanOrEqual(width + 1);
}
for (const config of configurations) zoomTest(`${config.designSystem} ${config.colorMode} DatePicker at real 200%`, {
    tag: ['@rc-date-picker', '@environment', '@chromium-only'],
    annotation: { type: 'environment', description: JSON.stringify({ id: 'zoom-200', ...config }) },
}, async ({ page, previewOrigin, realZoom }, info) => {
    await page.clock.setFixedTime(new Date('2026-06-16T04:00:00Z'));
    await openDemo(page, previewOrigin, 'rc-date-picker', spec.demo, config);
    const frame = page.getByRole('region', { name: 'DatePicker visual matrix' });
    const input = frame.getByRole('textbox', { name: '计划日期', exact: true });
    const original = await input.elementHandle();
    await input.click();
    const dialog = page.getByRole('dialog');
    const selected = dialog.getByRole('button', { name: '2026-06-18', exact: true });
    await selected.click();
    await selected.press('Tab');
    const focusedDay = dialog.getByRole('button', { name: '2026-06-19', exact: true });
    await expect(focusedDay).toBeFocused();
    await realZoom.set200(page);
    expect(await input.evaluate((node, previous) => node === previous, original)).toBe(true);
    await expect(input).toHaveValue('2026-06-15');
    await expect(selected).toHaveAttribute('aria-pressed', 'true');
    await expect(focusedDay).toBeFocused();
    expect(await focusedDay.evaluate(node => node.matches(':focus-visible'))).toBe(true);
    await focusedDay.scrollIntoViewIfNeeded();
    await settleFiniteAnimations(page);
    const viewport = await page.evaluate(() => ({ width: globalThis.innerWidth, height: globalThis.innerHeight }));
    const bounds = await focusedDay.boundingBox();
    expect(viewport.width).toBeLessThanOrEqual(640);
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(viewport.width + 1);
    await expect(focusedDay).toBeInViewport();
    await expectPopupWithinWidth(page, dialog);
    await captureZoom(page, realZoom, `${config.designSystem}-${config.colorMode}-zoom-200-calendar-draft.png`, info);
    const confirm = dialog.getByRole('button', { name: '确定', exact: true });
    for (let step = 0; step < 60 && !await confirm.evaluate(node => node === node.ownerDocument.activeElement); step += 1) await page.keyboard.press('Tab');
    await expect(confirm).toBeFocused();
    await confirm.scrollIntoViewIfNeeded();
    await expect(confirm).toBeInViewport();
    await expect(selected).toHaveAttribute('aria-pressed', 'true');
    await settleFiniteAnimations(page);
    await captureZoom(page, realZoom, `${config.designSystem}-${config.colorMode}-zoom-200-calendar-actions.png`, info);
    await confirm.press('Enter');
    await expect(dialog).toHaveCount(0);
    await expect(input).toHaveValue('2026-06-18');

    const seconds = frame.getByRole('textbox', { name: '秒精度时间', exact: true });
    const committed = await seconds.inputValue();
    await seconds.scrollIntoViewIfNeeded();
    await seconds.click();
    const hour = dialog.locator('[data-time-part="hour"] input');
    await hour.fill('10');
    await hour.press('ArrowUp');
    await hour.press('Tab');
    const minute = dialog.getByRole('textbox', { name: '分钟', exact: true });
    await expect(minute).toBeFocused();
    await minute.press('ArrowDown');
    await minute.press('Tab');
    const second = dialog.getByRole('textbox', { name: '秒', exact: true });
    await expect(second).toBeFocused();
    await second.press('ArrowUp');
    await second.press('Tab');
    await dialog.getByRole('radio', { name: '上午', exact: true }).press('ArrowRight');
    const period = dialog.getByRole('radio', { name: '下午', exact: true });
    await expect(period).toBeFocused();
    await expect(period).toHaveAttribute('aria-checked', 'true');
    await expect(hour).toHaveValue('11');
    await expect(minute).toHaveValue('29');
    await expect(second).toHaveValue('16');
    await expect(seconds).toHaveValue(committed);
    await period.scrollIntoViewIfNeeded();
    await expect(period).toBeInViewport();
    await expectPopupWithinWidth(page, dialog);
    await settleFiniteAnimations(page);
    await captureZoom(page, realZoom, `${config.designSystem}-${config.colorMode}-zoom-200-time-input-draft.png`, info);
    await page.keyboard.press('Escape');
    await expect(dialog).toHaveCount(0);
    await expect(seconds).toHaveValue(committed);

    const dialField = frame.getByRole('textbox', { name: '表盘时间', exact: true });
    await dialField.scrollIntoViewIfNeeded();
    await dialField.click();
    await expect(dialog.locator('[data-mode]')).toHaveAttribute('data-mode', 'input');
    const dialHour = dialog.locator('[data-time-part="hour"] input');
    await dialHour.press('Tab');
    await page.keyboard.press('Tab');
    const cancel = dialog.getByRole('button', { name: '取消', exact: true });
    await expect(cancel).toBeFocused();
    await cancel.scrollIntoViewIfNeeded();
    await expect(cancel).toBeInViewport();
    await expectPopupWithinWidth(page, dialog);
    await settleFiniteAnimations(page);
    await captureZoom(page, realZoom, `${config.designSystem}-${config.colorMode}-zoom-200-time-dial-fallback.png`, info);
    await cancel.press('Enter');
    await expect(dialog).toHaveCount(0);

    const dateTime = frame.getByRole('textbox', { name: '计划日期时间', exact: true });
    await dateTime.scrollIntoViewIfNeeded();
    const committedDateTime = await dateTime.inputValue();
    await dateTime.click();
    const dateTimeDraft = dialog.getByRole('button', { name: '2026-06-18', exact: true });
    await dateTimeDraft.click();
    await dateTimeDraft.press('Tab');
    const dateTimeFocus = dialog.getByRole('button', { name: '2026-06-19', exact: true });
    await expect(dateTimeFocus).toBeFocused();
    await dateTimeFocus.scrollIntoViewIfNeeded();
    await expect(dateTimeFocus).toBeInViewport();
    await expectPopupWithinWidth(page, dialog);
    await settleFiniteAnimations(page);
    await captureZoom(page, realZoom, `${config.designSystem}-${config.colorMode}-zoom-200-datetime-calendar.png`, info);
    const dateTimeHour = dialog.locator('[data-time-part="hour"] input');
    await dateTimeHour.fill('10');
    await dateTimeHour.press('Tab');
    await page.keyboard.press('Tab');
    await page.keyboard.press('Tab');
    await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused();
    await dialog.getByRole('button', { name: '取消', exact: true }).scrollIntoViewIfNeeded();
    await expect(dateTimeDraft).toHaveAttribute('aria-pressed', 'true');
    await expect(dateTimeHour).toHaveValue('10');
    await expect(dateTime).toHaveValue(committedDateTime);
    await settleFiniteAnimations(page);
    await captureZoom(page, realZoom, `${config.designSystem}-${config.colorMode}-zoom-200-datetime-scroll-actions.png`, info);
});
