import { Buffer } from 'node:buffer';
import { test, expect, configurations, openDemo, readVisualSpec, captureVisual } from '../../../test/visual/component-fixture.mjs';
import { waitForFlowPresentation } from './flow-diagram.visual-helpers.mjs';
const spec = await readVisualSpec(import.meta.url);

for (const config of configurations) test(`${config.designSystem} ${config.colorMode} public fit pan domain zoom and PNG export`, { tag: ['@rc-flow-diagram', '@interaction', '@domain-controls'] }, async ({ page, browserName, previewOrigin }, info) => {
    await openDemo(page, previewOrigin, 'rc-flow-diagram', spec.demo, config);
    const scene = page.getByRole('region', { name: 'FlowDiagram visual matrix' }), status = scene.getByLabel('布局状态');
    await expect(status).toHaveAttribute('data-layout', 'ready'); await waitForFlowPresentation(scene, { labels: true });
    const positions = await status.getAttribute('data-node-rects'), routes = await status.getAttribute('data-routes');
    await scene.getByRole('button', { name: '放大流程图', exact: true }).click();
    await expect.poll(async () => Number(await status.getAttribute('data-zoom'))).toBeGreaterThan(1);
    const enlarged = Number(await status.getAttribute('data-zoom'));
    await scene.getByRole('button', { name: '缩小流程图', exact: true }).click();
    await expect.poll(async () => Number(await status.getAttribute('data-zoom'))).toBeLessThan(enlarged);
    await scene.getByRole('button', { name: '适应流程图', exact: true }).click(); await waitForFlowPresentation(scene);
    const fitZoom = await status.getAttribute('data-zoom');
    await scene.getByRole('button', { name: '导出流程图 PNG', exact: true }).click();
    const image = scene.getByRole('img', { name: '导出的流程图 PNG', exact: true });
    await expect(image).toBeVisible();
    await image.evaluate(node => node.decode());
    expect(await image.evaluate(node => node.complete && node.naturalWidth > 0 && node.naturalHeight > 0)).toBe(true);
    const beforePan = await image.getAttribute('src');
    const canvas = scene.locator('canvas').first();
    await canvas.scrollIntoViewIfNeeded();
    const bounds = await canvas.boundingBox();
    await page.mouse.move(bounds.x + bounds.width - 16, bounds.y + bounds.height - 16); await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width - 60, bounds.y + bounds.height - 45, { steps: 6 }); await page.mouse.up();
    await waitForFlowPresentation(scene);
    await scene.getByRole('button', { name: '导出流程图 PNG', exact: true }).click();
    await expect(image).not.toHaveAttribute('src', beforePan);
    await image.evaluate(node => node.decode());
    await waitForFlowPresentation(scene);
    await expect(status).toHaveAttribute('data-zoom', fitZoom);
    await expect(status).toHaveAttribute('data-node-rects', positions); await expect(status).toHaveAttribute('data-routes', routes);
    const png = Buffer.from((await image.getAttribute('src')).split(',')[1], 'base64');
    expect([...png.subarray(0, 8)]).toEqual([137, 80, 78, 71, 13, 10, 26, 10]);
    await info.attach('public-export-png', { body: png, contentType: 'image/png' });
    await captureVisual(scene, `${config.designSystem}-${config.colorMode}-domain-controls.png`, info, browserName);
});
